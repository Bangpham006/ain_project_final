"""Evidence for the oral-defence questions (`reasoning_probe`) of every fixture.

Run from anywhere:   python experiments/reasoning_probes.py [output_dir]
Writes to:           experiments/results/reasoning_probes.md by default

Nothing here is a hand-written answer: for each fixture the script runs the
core and reports facts the probe asks about -- rules fired, conflict
resolution, what changes if a symptom named in the probe is added, the
minimal subsets of the reported symptoms that still give the same
diagnosis, the follow-up questions the engine would ask, and the remediation
text of the preferred cause(s). The spoken answer is the team's job.
"""

from __future__ import annotations

import itertools
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "starter"))

import conflicts as conflicts_mod  # noqa: E402
import rule_loader  # noqa: E402
import student_core as core  # noqa: E402

# Windows consoles and pipes default to cp1252, which cannot print Vietnamese paths or ∧ →.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "experiments" / "results"
KB = rule_loader.load_all(ROOT / "data")
RULES = KB["rules"]
RULE_BY_ID = {r["id"]: r for r in RULES}
SYMPTOMS = {s["id"]: s for s in KB["symptoms"]}
CAUSES = {c["id"]: c for c in KB["causes"]}
CONFLICTS = conflicts_mod.load_conflicts(ROOT / "data" / "conflicts.json", set(SYMPTOMS))

lines: list[str] = []


def emit(line: str = "") -> None:
    lines.append(line)


def fmt(ids) -> str:
    ids = list(ids)
    return "{" + ", ".join(sorted(ids)) + "}" if ids else "{}"


def rule_text(rule_id: str) -> str:
    r = RULE_BY_ID[rule_id]
    comment = f" -- {r['comment']}" if r.get("comment") else ""
    return f"`{rule_id}`: {' ∧ '.join(r['if'])} → {r['then']}{comment}"


def same_diagnosis(a: dict, b: dict) -> bool:
    return a["status"] == b["status"] and sorted(r["cause_id"] for r in a["results"]) == sorted(
        r["cause_id"] for r in b["results"]
    )


emit("# Reasoning probes -- evidence for the oral defence (generated by experiments/reasoning_probes.py)")
emit()
emit(f"Conflict resolution: `{core.DEFAULT_STRATEGY}`. Conflict table: `data/conflicts.json` ({len(CONFLICTS)} pairs).")
emit()

for sc in KB["scenarios"]:
    s = sc["presented_symptoms"]
    rep = core.diagnose(s, RULES, CONFLICTS)
    emit(f"## {sc['id']}  (`{sc['class']}`, {sc['domain']})")
    emit()
    emit(f"> **Probe:** {sc.get('reasoning_probe', '-')}")
    emit()
    emit(f"- Reported: {s or '(nothing)'}")
    emit(f"- Status: **{rep['status']}**; preferred: {fmt(rep['leaders'])}")
    for r in rep["results"]:
        emit(f"- {r['cause_id']} via {', '.join(r['fired_rules'])} "
             f"(support {r['supporting_symptoms']}, specificity {r['specificity']})")
    if rep["conflicts"]:
        for c in rep["conflicts"]:
            emit(f"- Conflict {c['id']}: {' vs '.join(c['symptoms'])} -- {c['reason']}")
    emit()

    named_rules = [rid for rid in dict.fromkeys(re.findall(r"R\d{3}", sc.get("reasoning_probe", ""))) if rid in RULE_BY_ID]
    if named_rules:
        emit("Rules named in the probe:")
        for rid in named_rules:
            emit(f"- {rule_text(rid)}")
        emit()

    named_syms = [x for x in dict.fromkeys(re.findall(r"SYM\d{2}", sc.get("reasoning_probe", ""))) if x not in s]
    for extra in named_syms:
        after = core.diagnose(s + [extra], RULES, CONFLICTS)
        before_rules = {rid for r in rep["results"] for rid in r["fired_rules"]}
        new_rules = [rid for r in after["results"] for rid in r["fired_rules"] if rid not in before_rules]
        changed = "unchanged" if same_diagnosis(rep, after) else "**changed**"
        emit(f"What if {extra} ({SYMPTOMS[extra]['description']}) is added? "
             f"New rules: {', '.join(new_rules) or 'none'}; candidates {fmt(r['cause_id'] for r in after['results'])}; "
             f"status {after['status']} -> diagnosis {changed}.")
        for rid in new_rules:
            emit(f"- {rule_text(rid)}")
        emit()

    if len(s) > 1:
        minimal: list[tuple[str, ...]] = []
        for k in range(1, len(s)):
            for subset in itertools.combinations(s, k):
                if same_diagnosis(core.diagnose(list(subset), RULES, CONFLICTS), rep) and not any(
                    set(m) <= set(subset) for m in minimal
                ):
                    minimal.append(subset)
        emit(f"Minimal subsets of the reported symptoms giving the same diagnosis: "
             f"{', '.join(str(list(m)) for m in minimal) or 'none -- every reported symptom is needed'}.")
        emit()

    domain_ids = [x for x, sym in SYMPTOMS.items() if sym["domain"] == sc["domain"]]
    followups = core.suggest_followups(s, RULES, CONFLICTS, candidates=domain_ids)
    if followups:
        emit(f"Follow-up questions within {sc['domain']} (most decisive first):")
        emit()
        emit("| ask about | description | status if confirmed | preferred | new rules |")
        emit("|---|---|---|---|---|")
        for f in followups:
            emit(f"| {f['symptom']} | {SYMPTOMS[f['symptom']]['description']} | {f['status']} | "
                 f"{fmt(f['leaders'])} | {', '.join(f['new_rules'])} |")
        emit()
    if rep["status"] == "insufficient_evidence":
        ties = [f for f in core.suggest_followups(s, RULES, CONFLICTS) if f["status"] == "ambiguous"]
        emit(f"Across all domains, single symptoms that would produce a tie: "
             f"{', '.join(f['symptom'] + ' ' + fmt(f['leaders']) for f in ties) or 'none'}.")
        emit()

    for cause_id in rep["leaders"]:
        action = CAUSES[cause_id].get("recommended_action", "-")
        emit(f"Remediation for {cause_id} ({CAUSES[cause_id]['description']}): {action}")
    if rep["leaders"]:
        emit()

OUT.mkdir(parents=True, exist_ok=True)
(OUT / "reasoning_probes.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT / 'reasoning_probes.md'} ({len(lines)} lines)")
