def table(headers: list[str], rows: list[list]) -> None:
    emit("| " + " | ".join(headers) + " |")
    emit("|" + "|".join("---" for _ in headers) + "|")
    for row in rows:
        emit("| " + " | ".join(str(c) for c in row) + " |")
